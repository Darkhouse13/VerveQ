// BALLON D'OR BY CLUB — timing truth. Reads the gated facts
// (src/lab/race/facts.json, written by lab/race-facts.mjs) and writes
// src/lab/race/timeline.json: one segment per year with its frame window,
// the standings after it and the drama event it carries. The composition,
// the sound bed (lab/race-audio.mjs) and the gate (lab/race-verify.mjs) all
// read this one file — re-time here, never in three places.
//
// Pacing law (brief): ~0.5s a year, faster where the table doesn't move,
// slower where it does. Lead changes are the drama and get the longest beat.
//
// Ranking: count desc, ties broken by who reached that count FIRST (the
// standard race convention — a club that draws level does not take the lead,
// it has to pass). Tied clubs share a displayed rank.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const FACTS = path.join(dir, "..", "src", "lab", "race", "facts.json");
const OUT = path.join(dir, "..", "src", "lab", "race", "timeline.json");

export const FPS = 30;
export const VISIBLE = 10; // rows on the board — the final top 10 closes on a four-way tie at 2
export const BEAT = {
  first: 14, // 1956: frame 0 is already the board — move on inside the hook window
  quiet: 10, // table order unchanged
  step: 17, // the winner's club climbs, or a new club enters the board
  level: 26, // draws level with the leader
  lead: 42, // new leader
  gap: 27, // 2020 not awarded
  last: 30, // 2025 lands
};
export const SETTLE = 20; // after 2025: the board settles into the final table
export const FREEZE = 90; // the final table held dead still (≥2s law)
export const CLOSER = 120;

export const buildTimeline = () => {
  const facts = JSON.parse(readFileSync(FACTS, "utf8"));
  const counts = {};
  const reached = {}; // club → year it reached its current count
  const firstWin = {};
  let order = [];
  let frame = 0;
  const segs = [];
  const rank = () =>
    Object.keys(counts).sort((a, b) => counts[b] - counts[a] || reached[a] - reached[b] || firstWin[a] - firstWin[b]);
  for (const y of facts.years) {
    const prev = order;
    const prevLeader = prev[0] ?? null;
    let event = null;
    if (y.awarded) {
      counts[y.club] = (counts[y.club] ?? 0) + 1;
      reached[y.club] = y.year;
      firstWin[y.club] ??= y.year;
      order = rank();
      const leader = order[0];
      const oldPos = prev.indexOf(y.club);
      const newPos = order.indexOf(y.club);
      if (prevLeader && leader !== prevLeader) event = "lead";
      else if (order.length > 1 && counts[order[1]] === counts[order[0]] && y.club === order[1]) event = "level";
      else if (oldPos === -1 ? newPos < VISIBLE : newPos < oldPos && newPos < VISIBLE) event = "step";
    }
    const dur =
      segs.length === 0 ? BEAT.first : !y.awarded ? BEAT.gap : y.year === facts.years.at(-1).year ? BEAT.last : event === "lead" ? BEAT.lead : event === "level" ? BEAT.level : event === "step" ? BEAT.step : BEAT.quiet;
    segs.push({
      year: y.year,
      awarded: y.awarded,
      winner: y.winner ?? null,
      club: y.club ?? null,
      event,
      from: frame,
      dur,
      counts: { ...counts },
      order: [...order],
      leader: order[0] ?? null,
    });
    frame += dur;
  }
  const RACE = frame;
  const finalOrder = segs.at(-1).order;
  const finalCounts = segs.at(-1).counts;
  const rankLabel = [];
  finalOrder.forEach((c, i) => rankLabel.push(i > 0 && finalCounts[c] === finalCounts[finalOrder[i - 1]] ? rankLabel[i - 1] : i + 1));
  return {
    _doc: "Generated by lab/race-timeline.mjs from src/lab/race/facts.json. Do not edit.",
    fps: FPS,
    visible: VISIBLE,
    race: RACE,
    settle: SETTLE,
    freeze: FREEZE,
    closer: CLOSER,
    finalFrom: RACE,
    closerFrom: RACE + SETTLE + FREEZE,
    total: RACE + SETTLE + FREEZE + CLOSER,
    final: finalOrder.slice(0, VISIBLE).map((c, i) => ({ club: c, count: finalCounts[c], rank: rankLabel[i] })),
    segs,
  };
};

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const t = buildTimeline();
  writeFileSync(OUT, JSON.stringify(t, null, 1));
  const ev = t.segs.filter((s) => s.event === "lead" || s.event === "level");
  console.log(`race-timeline: race ${(t.race / FPS).toFixed(1)}s + settle ${(t.settle / FPS).toFixed(1)}s + freeze ${(t.freeze / FPS).toFixed(1)}s + closer ${(t.closer / FPS).toFixed(1)}s = ${(t.total / FPS).toFixed(1)}s`);
  for (const s of ev) console.log(`  ${s.year} ${s.event.toUpperCase().padEnd(5)} ${s.club} (${s.counts[s.club]}) — leader ${s.leader}`);
  console.log("final:", t.final.map((f) => `${f.rank}. ${f.club} ${f.count}`).join(" | "));
  console.log(`→ ${OUT}`);
}
