/**
 * Writes src/styles/tokens.json from src/index.css (VerveQ ONE P4.5).
 *
 * index.css is where the brand's colors are defined; tokens.json is the same
 * values in a form anything outside the app can import without parsing CSS —
 * the content factory (reels, carousels, OG art) is meant to read its palette
 * from here instead of restating hex values. docs/BRAND.md explains the roles.
 *
 *   node scripts/exportTokens.mjs          write the file
 *   node scripts/exportTokens.mjs --check  exit 1 if it is stale
 *
 * src/test/designTokens.test.ts fails when the committed file drifts from
 * index.css, so a token edit without a re-export cannot land.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { APP, hslToHex } from "./lib/brand.mjs";

export const TOKENS_PATH = path.join(APP, "src/styles/tokens.json");

/**
 * The innermost rule blocks of a stylesheet, as { selectors, decls }.
 * Enough for index.css: tokens live in flat blocks with no nesting.
 */
function blocks(css) {
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const out = [];
  for (const m of clean.matchAll(/([^{}]*)\{([^{}]*)\}/g)) {
    const selectors = m[1].split(",").map((s) => s.trim()).filter(Boolean);
    const decls = {};
    for (const d of m[2].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) decls[d[1]] = d[2].trim();
    out.push({ selectors, decls });
  }
  return out;
}

function findBlock(all, selectorList) {
  const b = all.find(
    (x) => x.selectors.length === selectorList.length && selectorList.every((s) => x.selectors.includes(s)),
  );
  if (!b) throw new Error(`no block for "${selectorList.join(", ")}" in src/index.css`);
  return b.decls;
}

function color(raw, scope, name) {
  let value = raw;
  for (let i = 0; i < 4; i++) {
    const ref = value.match(/^var\((--[\w-]+)\)$/);
    if (!ref) break;
    value = scope[ref[1]];
    if (value === undefined) throw new Error(`${name}: unresolved ${ref[1]}`);
  }
  const m = value.match(/^([\d.]+)\s+([\d.]+)%\s+([\d.]+)%$/);
  if (!m) throw new Error(`${name}: "${raw}" is not an HSL triple`);
  const [h, s, l] = [Number(m[1]), Number(m[2]), Number(m[3])];
  return { hsl: `${h} ${s}% ${l}%`, hex: hslToHex(h, s, l) };
}

/** Brand palette: name → [css var, role]. */
const PALETTE = {
  ink: ["--ink", "The ground of every screen and image; text on any colored fill."],
  cream: ["--cream", "Text on ink; the ground of long-form reading cards."],
  lime: ["--lime", "The ONE action color: the thing to tap, small accents. Never a large fill, never a shadow."],
  blue: ["--electric-blue", "Mode accent: Who's Older."],
  pink: ["--hot-pink", "Mode accent: Missing Letters."],
  yellow: ["--yellow", "Mode accent / highlight chips."],
  orange: ["--orange", "Mode accent (legacy primary); the action on cream reading cards."],
  right: ["--right", "Answer feedback only: correct."],
  wrong: ["--wrong", "Answer feedback only: wrong."],
};

/** Semantic roles per theme → css var. */
const ROLES = [
  "--background", "--foreground", "--card", "--card-foreground", "--muted", "--muted-foreground",
  "--border", "--primary", "--primary-foreground", "--action", "--action-foreground",
];

const camel = (v) => v.replace(/^--/, "").replace(/-(\w)/g, (_, c) => c.toUpperCase());

export function buildTokens(css = readFileSync(path.join(APP, "src/index.css"), "utf8")) {
  const all = blocks(css);
  const constants = findBlock(all, [":root"]);
  const ink = { ...constants, ...findBlock(all, [":root", ".theme-ink", ".theme-weekend", ".theme-older", ".theme-letters"]) };
  const paper = { ...ink, ...findBlock(all, [".theme-paper"]) };

  const palette = {};
  for (const [name, [v, role]] of Object.entries(PALETTE)) {
    if (ink[v] === undefined) throw new Error(`palette ${name}: ${v} not defined on the ink ground`);
    palette[name] = { ...color(ink[v], ink, name), var: v, role };
  }
  const theme = (scope) =>
    Object.fromEntries(
      ROLES.filter((v) => scope[v] !== undefined).map((v) => [camel(v), { ...color(scope[v], scope, v), var: v }]),
    );

  const tailwind = readFileSync(path.join(APP, "tailwind.config.ts"), "utf8");
  const tracking = tailwind.match(/brand:\s*"([\d.]+em)"/);
  if (!tracking) throw new Error("tracking `brand` not found in tailwind.config.ts");

  return {
    $comment:
      "GENERATED by app/scripts/exportTokens.mjs from app/src/index.css — do not edit; change index.css and re-run. The single source the content factory imports for the VerveQ brand. Roles and rules: docs/BRAND.md.",
    palette,
    theme: { ink: theme(ink), paper: theme(paper) },
    type: {
      heading: { family: "Space Grotesk", weight: 700, files: "app/public/fonts/space-grotesk-*.woff2" },
      mono: { family: "JetBrains Mono", weight: 700, files: "app/public/fonts/jetbrains-mono-*.woff2" },
      staticTtf: "app/scripts/og/fonts/*-700.ttf",
      wordmarkTracking: tracking[1],
    },
    radius: ink["--radius"],
    mark: {
      geometry: "app/src/components/ui/brandMark.geometry.json",
      svg: {
        mark: "app/public/brand/verveq-mark.svg",
        lockupOnCream: "app/public/brand/verveq-lockup.svg",
        lockupOnInk: "app/public/brand/verveq-lockup-cream.svg",
      },
      tiltDeg: -4,
    },
  };
}

export function serialize(tokens) {
  return JSON.stringify(tokens, null, 2) + "\n";
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = serialize(buildTokens());
  if (process.argv.includes("--check")) {
    let cur = "";
    try {
      cur = readFileSync(TOKENS_PATH, "utf8");
    } catch {
      /* missing = stale */
    }
    if (cur !== next) {
      console.error("src/styles/tokens.json is stale — run: node scripts/exportTokens.mjs");
      process.exit(1);
    }
    console.log("src/styles/tokens.json is current");
  } else {
    writeFileSync(TOKENS_PATH, next);
    console.log(`wrote src/styles/tokens.json (${next.length} bytes)`);
  }
}
